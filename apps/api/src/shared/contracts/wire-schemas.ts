/** Explicit public wire shapes. Database models and credentials are never inferred into this registry. */
export type Schema = Record<string, any>;
export const ref = (name: string): Schema => ({
  $ref: `#/components/schemas/${name}`,
});
export const obj = (
  properties: Record<string, Schema>,
  required = Object.keys(properties),
): Schema => ({
  type: "object",
  properties,
  required,
  additionalProperties: false,
});
export const arr = (items: Schema): Schema => ({ type: "array", items });
export const nullable = (schema: Schema): Schema => ({
  anyOf: [schema, { type: "null" }],
});
export const str: Schema = { type: "string" },
  uuid: Schema = { type: "string", format: "uuid" },
  integer: Schema = { type: "integer" },
  bool: Schema = { type: "boolean" },
  timestamp: Schema = { type: "string", format: "date-time" },
  decimal: Schema = { type: "string", pattern: "^-?[0-9]+$" };
